const form = document.getElementById("assessmentForm");
const reportList = document.getElementById("reportList");
const message = document.getElementById("message");

let reports = JSON.parse(
  localStorage.getItem("securityReports") || "[]"
);

function saveToStorage() {
  localStorage.setItem(
    "securityReports",
    JSON.stringify(reports)
  );
}

function updateStats() {
  document.getElementById("totalReports").textContent =
    reports.length;
  
  document.getElementById("highRisks").textContent =
    reports.filter(report =>
      report.risk === "High" ||
      report.risk === "Critical"
    ).length;
  
  document.getElementById("completed").textContent =
    reports.length;
}

function displayReports() {
  reportList.innerHTML = "";
  
  if (reports.length === 0) {
    reportList.innerHTML =
      '<p class="empty">No assessments saved yet.</p>';
    
    updateStats();
    return;
  }
  
  reports.forEach((report, index) => {
    const item = document.createElement("div");
    item.className = "report-item";
    
    const title = document.createElement("h3");
    title.textContent = report.project;
    
    const target = document.createElement("p");
    target.textContent = "Target: " + report.target;
    
    const type = document.createElement("p");
    type.textContent = "Assessment: " + report.type;
    
    const risk = document.createElement("span");
    risk.className = "risk " + report.risk.toLowerCase();
    risk.textContent = report.risk + " Risk";
    
    const finding = document.createElement("p");
    finding.textContent = "Finding: " + report.finding;
    
    const solution = document.createElement("p");
    solution.textContent = "Recommendation: " + report.solution;
    
    const date = document.createElement("p");
    date.textContent = "Date: " + report.date;
    
    const actions = document.createElement("div");
    actions.className = "report-actions";
    
    const downloadBtn = document.createElement("button");
    downloadBtn.textContent = "Download Report";
    downloadBtn.type = "button";
    downloadBtn.addEventListener("click", () => {
      downloadReport(index);
    });
    
    const deleteBtn = document.createElement("button");
    deleteBtn.textContent = "Delete";
    deleteBtn.type = "button";
    deleteBtn.addEventListener("click", () => {
      deleteReport(index);
    });
    
    actions.append(downloadBtn, deleteBtn);
    
    item.append(
      title,
      target,
      type,
      risk,
      finding,
      solution,
      date,
      actions
    );
    
    reportList.appendChild(item);
  });
  
  updateStats();
}

form.addEventListener("submit", function(event) {
  event.preventDefault();
  
  const report = {
    project: document.getElementById("projectName").value.trim(),
    target: document.getElementById("target").value.trim(),
    type: document.getElementById("assessmentType").value,
    risk: document.getElementById("riskLevel").value,
    finding: document.getElementById("vulnerability").value.trim(),
    solution: document.getElementById("recommendation").value.trim(),
    date: new Date().toLocaleString()
  };
  
  reports.unshift(report);
  saveToStorage();
  displayReports();
  
  message.textContent = "Assessment saved successfully!";
  message.style.color = "#15803d";
  
  form.reset();
});

function deleteReport(index) {
  reports.splice(index, 1);
  saveToStorage();
  displayReports();
  
  message.textContent = "Assessment deleted successfully!";
  message.style.color = "#15803d";
}

function downloadReport(index) {
  const report = reports[index];
  
  const content = `
SECURITY ASSESSMENT REPORT
==========================

Project Name: ${report.project}

Target: ${report.target}

Assessment Type: ${report.type}

Risk Level: ${report.risk}

Security Finding:
${report.finding}

Recommended Solution:
${report.solution}

Assessment Date:
${report.date}

Generated by SecureReport
  `;
  
  const blob = new Blob([content], {
    type: "text/plain"
  });
  
  const url = URL.createObjectURL(blob);
  
  const link = document.createElement("a");
  link.href = url;
  link.download = "Security-Assessment-Report.txt";
  
  document.body.appendChild(link);
  link.click();
  link.remove();
  
  URL.revokeObjectURL(url);
}

document.getElementById("clearBtn").addEventListener("click", function() {
  if (reports.length === 0) {
    message.textContent = "No reports to clear.";
    message.style.color = "#dc2626";
    return;
  }
  
  if (confirm("Are you sure you want to delete all assessments?")) {
    reports = [];
    saveToStorage();
    displayReports();
    
    message.textContent = "All assessments cleared.";
    message.style.color = "#15803d";
  }
});

displayReports();